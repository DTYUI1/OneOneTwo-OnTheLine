// Содержание приветствия для каждой роли (28.09): обучаемому — порядок работы с
// карточкой, преподавателю — порядок проведения занятия, администратору — что
// проверить перед занятием. Разметка общая (WelcomeGate), здесь только слова.
import type { User } from "./api";
import { WORKFLOW_STEPS, type WorkflowStepId } from "./workflow";

export interface WelcomeStep {
  readonly title: string;
  readonly action: string;
}

export interface WelcomePhase {
  readonly title: string;
  readonly steps: readonly WelcomeStep[];
}

export interface WelcomeContent {
  readonly eyebrow: string;
  /** Продолжение фразы после имени: «Имя, …». */
  readonly lead: string;
  readonly begin: string;
  readonly safe: string;
  readonly pathTitle: string;
  readonly pathNote: string;
  readonly phases: readonly WelcomePhase[];
  readonly tip: string;
}

function workflow(ids: readonly WorkflowStepId[]): WelcomeStep[] {
  return ids.map((id) => {
    const step = WORKFLOW_STEPS.find((item) => item.id === id);
    if (!step) throw new Error(`Нет шага порядка работы: ${id}`);
    return step;
  });
}

