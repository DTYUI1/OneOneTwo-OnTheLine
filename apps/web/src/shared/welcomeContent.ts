export function welcomeContent(role: User["role"]): WelcomeContent {
  if (role === "teacher") return TEACHER;
  if (role === "admin") return ADMIN;
  return TRAINEE;
}

/** Сведения о рабочем месте: обучаемому — место и служба, остальным — роль. */
export function welcomeSeat(user: User): [string, string][] {
  if (user.role === "trainee")
    return [
      [
        "Рабочее место",
        user.workstation_number ? `АРМ ${user.workstation_number}` : "—",
      ],
      ["Служба ДДС", user.dds_service_id ?? "—"],
      ["Логин", user.login],
    ];
  return [
    ["Роль", user.role === "teacher" ? "Преподаватель" : "Администратор"],
    ["Логин", user.login],
  ];
}
