import type { DispatcherStatus } from "../cardModel";

/** Статус, который ставит показ на шаге проводника; null — шаг не про статус. */
export function demoStatus(
  step: string | null,
  rejected: boolean,
): DispatcherStatus | null {
  if (rejected || step === "decide") return "accepted";
  if (
    step === "responding" ||
    step === "arrived" ||
    step === "working" ||
    step === "completed"
  )
    return step;
  return null;
}

