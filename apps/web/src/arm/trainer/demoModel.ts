/** Комментарий к статусу в показе: суть доклада бригады или решения. */
export function demoComment(
  status: DispatcherStatus,
  summary: string,
  lastReport: string | null,
): string {
  if (status === "accepted") return `Принята к исполнению. ${summary}`.trim();
  return lastReport?.trim() || summary;
}

/** Пауза на прочтение фразы показа (`readMs` макета). */
export function readMs(text: string): number {
  return Math.max(1600, text.length * 55);
}
