// Набор номера кнопками (HQ-023): клавиатура окна телефона дописывает в то же поле «Номер»,
// что и клавиатура компьютера, — звонок идёт тем же путём (`dialNumber` → `dialOut`).
// Правила — чистые функции без браузера (проверяются тестами), вид — DialPad.tsx.

/**
 * Цифровые кнопки клавиатуры построчно: 1 2 3 / 4 5 6 / 7 8 9 / _ 0 ⌫. «*» и «#» в ДДС роли не
 * играют — их нет (решение 18.10); нижний ряд — пустое место, «0» и «стереть» (DialPad.tsx).
 */
export const DIAL_KEYS = [
  "1",
  "2",
  "3",
  "4",
  "5",
  "6",
  "7",
  "8",
  "9",
  "0",
] as const;

export type DialKey = (typeof DIAL_KEYS)[number];

/** Кнопка дописывает свой знак в конец набранного — как ввод с клавиатуры компьютера. */
export function pressKey(value: string, key: DialKey): string {
  return value + key;
}

/**
 * «Стереть» (⌫ в сетке клавиатуры) убирает последнюю набранную цифру (или `*`, `#`, `+`,
 * набранные с клавиатуры компьютера) вместе с оформлением после неё:
 * из «+7 (495) 103-» уходит «3-», из «10» — «0». Без цифр поле становится пустым.
 */
export function eraseLast(value: string): string {
  const erased = value.replace(/[\d*#+][^\d*#+]*$/, "");
  return erased === value ? "" : erased;
}
