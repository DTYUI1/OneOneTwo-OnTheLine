def _and(items: list[str]) -> str:
    return items[0] if len(items) == 1 else f"{', '.join(items[:-1])} и {items[-1]}"


def comment_facts_missing(missing: list[tuple[str, str]]) -> Remark:
    """Не хватает пунктов комментария: [(вид пункта, подпись)]; последствие — по первому.

    Слова преподавателя (вид keywords, подпись «Ключевые слова: …») называются сами собой.
    """
    names: list[str] = []
    what: list[str] = []
    for kind, text in missing:
        name, _, _, need = _FACTS.get(kind, _FACTS["keywords"])
        if kind == "keywords" and ": " in text:
            name = need = f"«{text.split(': ', 1)[1]}»"
        names.append(name)
        what.append(need)
    _, consequence, page, _ = _FACTS.get(missing[0][0], _FACTS["keywords"])
    return Remark(
        f"В комментарии нет: {', '.join(dict.fromkeys(names))}.",
        consequence,
        page,
        f"Повторите: в комментарии рядом со статусом напишите {_and(list(dict.fromkeys(what)))}.",
    )


