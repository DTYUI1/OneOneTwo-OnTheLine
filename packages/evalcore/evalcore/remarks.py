def missing_status(state: str) -> Remark:
    consequence, page, repeat = _MISSING.get(
        state,
        (
            "Ход работ в карточке не совпадает с фактом: другие службы видят неверную картину.",
            MEMO_PROGRESS,
            "Повторите: ставьте статус по каждому докладу бригады.",
        ),
    )
    return Remark(f"Не поставлен статус {label(state)}.", consequence, page, repeat)


