def label(state: str) -> str:
    return f"«{STATE_LABELS.get(state, state)}»"


def labels(states: list[str]) -> str:
    return ", ".join(label(state) for state in states)


def seconds_text(value: float) -> str:
    """Секунды в родительном падеже: «в течение 30 секунд», «быстрее 3 секунд», «21 секунды»."""
    number = round(value)
    single = number % 10 == 1 and number % 100 != 11
    return f"{number} {'секунды' if single else 'секунд'}"


def fold(text: str) -> str:
    """Текст для поиска без регистра, «ё» и латинских двойников, той же длины.

    Позиция в свёрнутом тексте — позиция в исходном: по ней вырезается цитата.
    """
    lowered = (char.lower() if len(char.lower()) == 1 else char for char in cyrillic_twins(text))
    return "".join("е" if char == "ё" else char for char in lowered)


def quote_span(text: str, start: int, end: int, radius: int = QUOTE_RADIUS) -> str:
    """Фрагмент `text` вокруг [start, end): ±radius символов по границам слов, с «…» на срезе."""
    left = max(0, start - radius)
    right = min(len(text), end + radius)
    if left > 0:
        space = text.find(" ", left, start)
        left = space + 1 if space >= 0 else left
    if right < len(text):
        space = text.rfind(" ", end, right)
        right = space if space >= 0 else right
    fragment = " ".join(text[left:right].split())
    return f"{'…' if left > 0 else ''}{fragment}{'…' if right < len(text) else ''}"


def excerpt(text: str) -> str | None:
    """Начало сказанного или написанного целиком — до 2·QUOTE_RADIUS символов; пусто — None."""
    flat = " ".join(text.split())
    return quote_span(flat, 0, 0, 2 * QUOTE_RADIUS) if flat else None


def quote(text: str, needle: str, radius: int = QUOTE_RADIUS) -> str | None:
    """Цитата: первое вхождение `needle` в `text` без регистра, «ё» и двойников; нет — None."""
    wanted = fold(" ".join(needle.split()))
    if not wanted:
        return None
    flat = " ".join(text.split())
    found = fold(flat).find(wanted)
    if found < 0:
        return None
    return quote_span(flat, found, found + len(wanted), radius)


def quote_word(text: str, word: str, radius: int = QUOTE_RADIUS) -> str | None:
    """Цитата вокруг слова целиком (не части другого слова): «Дубининская», а не «ская»."""
    flat = " ".join(text.split())
    pattern = rf"(?<![0-9a-zа-я]){re.escape(fold(word))}(?![0-9a-zа-я])"
    match = re.search(pattern, fold(flat))
    return quote_span(flat, match.start(), match.end(), radius) if match else None


