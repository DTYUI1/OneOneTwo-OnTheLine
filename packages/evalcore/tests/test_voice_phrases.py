# Начальные формы слов фраз (в бою их даёт pymorphy2); остальные слова — сами себе форма.
LEMMAS = {
    "отправляю": "отправлять",
    "отправил": "отправлять",
    "высылаем": "высылать",
    "бескудниковского": "бескудниковский",
    "квартире": "квартира",
    "квартиры": "квартира",
    "изменилась": "измениться",
    "требуется": "требоваться",
    "жалуется": "жаловаться",
    "застряла": "застрять",
}


class Checker:
    """Словарь начальных форм без исправления опечаток."""

    def check(self, text: str) -> list:
        return []

    def lemmas(self, word: str) -> frozenset[str]:
        clean = word.casefold().replace("ё", "е")
        return frozenset({LEMMAS.get(clean, clean)})


def scenario(name: str) -> dict:
    return json.loads((SCENARIOS / f"{name}.json").read_text(encoding="utf-8"))


