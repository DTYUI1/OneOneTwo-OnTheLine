@pytest.mark.parametrize(("name", "text", "expected"), PHRASES)
def test_stand_phrase_gives_expected_parts(name, text, expected):
    assert voice_report_parts(scenario(name), text, Checker()) == tuple(expected)


def test_at_least_twenty_phrases():
    assert len(PHRASES) >= 20


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("дом двадцать четыре", "дом 24"),
        ("дом девяносто восемь", "дом 98"),
        ("квартира сто пятнадцать", "квартира 115"),
        ("дом девятьсот девяносто девять", "дом 999"),
        ("служба сто два", "служба 102"),
        ("Служба сто-3", "Служба 103"),
        ("дом один", "дом 1"),
        ("дом триста семь", "дом 307"),
    ],
)
def test_numbers_by_words_up_to_999(text, expected):
    assert spoken_numbers(text, Checker()) == expected
